"""Synthesised sounds for Space Racer (all original) and their sound events.

usage: sounds.py <addon_out_dir> <soundevents_template.vsndevts>
Writes sounds/spr/*.wav and soundevents/soundevents_addon.vsndevts (the template with our events added).
"""
import os, sys, math, wave
import numpy as np

OUT = sys.argv[1]
TEMPLATE = sys.argv[2] if len(sys.argv) > 2 else None
SR = 44100
rng = np.random.RandomState(5)

def t(sec): return np.arange(int(SR * sec)) / SR
def env(n, a=0.005, d=0.1, s=0.6, r=0.1, total=None):
    """ADSR over n samples"""
    out = np.zeros(n)
    ia, idd, ir = int(a * SR), int(d * SR), int(r * SR)
    iss = max(0, n - ia - idd - ir)
    k = 0
    out[k:k + ia] = np.linspace(0, 1, ia); k += ia
    out[k:k + idd] = np.linspace(1, s, idd); k += idd
    out[k:k + iss] = s; k += iss
    out[k:k + ir] = np.linspace(s, 0, min(ir, n - k))
    return out
def lowpass(x, cutoff):
    rc = 1 / (2 * math.pi * cutoff); dt = 1 / SR; a = dt / (rc + dt)
    y = np.zeros_like(x); acc = 0.0
    for i in range(len(x)):
        acc += a * (x[i] - acc); y[i] = acc
    return y
def highpass(x, cutoff): return x - lowpass(x, cutoff)
def sweep(f0, f1, sec, shape='sin'):
    tt = t(sec)
    f = f0 * (f1 / f0) ** (tt / sec)
    ph = 2 * math.pi * np.cumsum(f) / SR
    return np.sin(ph) if shape == 'sin' else np.sign(np.sin(ph))
def tone(f, sec, shape='sin'):
    tt = t(sec)
    return np.sin(2 * math.pi * f * tt) if shape == 'sin' else np.sign(np.sin(2 * math.pi * f * tt))
def noise(sec): return rng.uniform(-1, 1, int(SR * sec))
def norm(x, gain=0.9):
    m = np.abs(x).max() or 1
    return x / m * gain

SOUNDS = {}
def S(name, x): SOUNDS[name] = norm(x)

S('beep', tone(880, 0.16) * env(int(SR * 0.16), 0.003, 0.05, 0.5, 0.08))
S('go', (tone(1320, 0.55) + 0.4 * tone(1760, 0.55)) * env(int(SR * 0.55), 0.003, 0.1, 0.6, 0.3))
n = int(SR * 0.9); S('wreck', (lowpass(noise(0.9), 1200) * 1.6 + 0.6 * sweep(120, 35, 0.9)) * env(n, 0.002, 0.25, 0.4, 0.5))
arp = np.concatenate([tone(f, 0.18, 'sq') * env(int(SR * 0.18), 0.003, 0.05, 0.6, 0.05) for f in (523, 659, 784)] + [tone(1046, 0.4, 'sq') * env(int(SR * 0.4), 0.003, 0.1, 0.5, 0.25)])
S('finish', lowpass(arp, 3000))
n = int(SR * 0.45); S('warp', (sweep(400, 2600, 0.45) + 0.5 * sweep(800, 5200, 0.45)) * env(n, 0.01, 0.1, 0.7, 0.2))
S('lap', np.concatenate([tone(659, 0.14) * env(int(SR * 0.14), 0.003, 0.04, 0.6, 0.06), tone(988, 0.25) * env(int(SR * 0.25), 0.003, 0.05, 0.6, 0.15)]))
n = int(SR * 1.2); S('pulse', (sweep(90, 40, 1.2) + 0.3 * lowpass(noise(1.2), 400) + 0.25 * sweep(1800, 3600, 1.2)) * env(n, 0.05, 0.3, 0.5, 0.6))
n = int(SR * 0.3); S('pulsed', (tone(1568, 0.3) + 0.5 * tone(2349, 0.3) + 0.3 * tone(3136, 0.3)) * env(n, 0.002, 0.05, 0.4, 0.2))
n = int(SR * 0.14); S('hit', (lowpass(noise(0.14), 700) * 1.5 + 0.8 * tone(110, 0.14)) * env(n, 0.001, 0.04, 0.3, 0.08))
n = int(SR * 0.25); S('rail', (highpass(noise(0.25), 1500) * 0.8 + 0.7 * tone(930, 0.25) + 0.3 * tone(1870, 0.25)) * env(n, 0.001, 0.05, 0.3, 0.15))
n = int(SR * 0.45); S('scrape', lowpass(highpass(noise(0.45), 900), 4000) * env(n, 0.02, 0.1, 0.5, 0.2))
n = int(SR * 0.4); S('pad', (lowpass(noise(0.4), 2500) * 0.8 + 0.7 * sweep(500, 1100, 0.4)) * env(n, 0.005, 0.1, 0.6, 0.2))
n = int(SR * 0.7); S('fall', sweep(900, 90, 0.7) * env(n, 0.005, 0.1, 0.7, 0.3))
n = int(SR * 0.32); S('spin', (sweep(1400, 300, 0.32, 'sq') * 0.6 + 0.3 * sweep(2800, 600, 0.32)) * env(n, 0.002, 0.05, 0.6, 0.12))
S('reset', np.concatenate([tone(f, 0.08) * env(int(SR * 0.08), 0.002, 0.02, 0.6, 0.03) for f in (440, 660, 880)]))
n = int(SR * 0.8); wh = noise(0.8); S('boost', (lowpass(wh, 600) * np.linspace(0.3, 1.6, n) + 0.3 * highpass(wh, 3000) * np.linspace(0.1, 1, n) + 0.3 * sweep(180, 420, 0.8)) * env(n, 0.02, 0.2, 0.7, 0.3))
n = int(SR * 0.7); S('charge', (tone(220, 0.7) + 0.6 * tone(330, 0.7) + 0.3 * tone(440, 0.7) * (0.5 + 0.5 * np.sin(2 * math.pi * 7 * t(0.7)))) * env(n, 0.05, 0.1, 0.7, 0.3))

# ranges: how far each sound carries (units)
RANGE = {'beep': 5000, 'go': 6000, 'wreck': 3500, 'finish': 2500, 'warp': 2500, 'lap': 1200, 'pulse': 3500, 'pulsed': 1200,
         'hit': 1200, 'rail': 1200, 'scrape': 900, 'pad': 1500, 'fall': 1800, 'spin': 1500, 'reset': 1200, 'boost': 1800, 'charge': 1200}
VOL = {'scrape': 0.5, 'hit': 0.7, 'rail': 0.7, 'charge': 0.6, 'boost': 0.7, 'pulsed': 0.6}

d = os.path.join(OUT, 'sounds/spr'); os.makedirs(d, exist_ok=True)
for name, x in SOUNDS.items():
    with wave.open(os.path.join(d, name + '.wav'), 'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((x * 32000).astype(np.int16).tobytes())

ev = ['\t// ---- Space Racer sound events (generated by tools/sounds.py) ----']
for name in SOUNDS:
    r = RANGE[name]
    ev += ['\t"spr.%s" =' % name, '\t{', '\t\ttype = "csgo_mega"', '\t\tvolume = %.2f' % VOL.get(name, 0.85), '\t\tpitch = 1.0',
           '\t\tvsnd_files_track_01 = "sounds/spr/%s.vsnd"' % name,
           '\t\tdistance_volume_mapping_curve =', '\t\t[',
           '\t\t\t[', '\t\t\t\t0.0, 1.0, 0.0, 0.0,', '\t\t\t\t2.0, 3.0,', '\t\t\t],',
           '\t\t\t[', '\t\t\t\t%.1f, 1.0, 0.0, 0.0,' % (r * 0.2), '\t\t\t\t2.0, 3.0,', '\t\t\t],',
           '\t\t\t[', '\t\t\t\t%.1f, 0.0, 0.0, 0.0,' % r, '\t\t\t\t2.0, 3.0,', '\t\t\t],',
           '\t\t]', '\t}']
ev.append('\t// ---- end Space Racer ----')
body = '\n'.join(ev) + '\n'
os.makedirs(os.path.join(OUT, 'soundevents'), exist_ok=True)
if TEMPLATE and os.path.exists(TEMPLATE):
    tpl = open(TEMPLATE, encoding='utf-8').read()
    if '"spr.' in tpl:
        # already has ours (an addon file that was built before): replace the block
        a = tpl.index('\t// ---- Space Racer'); b = tpl.index('\t// ---- end Space Racer ----\n') + len('\t// ---- end Space Racer ----\n')
        tpl = tpl[:a] + tpl[b:]
    first = tpl.index('\n{') + 2
    text = tpl[:first] + body + tpl[first:]
else:
    text = ('<!-- kv3 encoding:text:version{e21c7f3c-8a33-41c5-9977-a76d3a32aa0d} format:generic:version{7412167c-06e9-4698-aff2-e63eb59037e7} -->\n{\n' + body + '}\n')
open(os.path.join(OUT, 'soundevents/soundevents_addon.vsndevts'), 'w', newline='\n', encoding='utf-8').write(text)
print('sounds', len(SOUNDS), 'events written')
